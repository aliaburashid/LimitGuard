-- ============================================================
-- 1. INITIALIZATION TRANSACTION AND SAFETY CHECKS
-- ============================================================

-- Start a transaction.
-- The database changes are committed together at the end.
BEGIN;

-- Use PostgreSQL's built-in catalog and the public schema.
SET LOCAL search_path = pg_catalog, public;

-- Prevent competing initialization processes from running
-- this baseline simultaneously.
SELECT pg_advisory_xact_lock(724211, 2);


-- Check whether the public schema already contains objects.
-- pg_class stores information about database objects.
-- pg_namespace identifies which schema an object belongs to.
--
-- The listed relkind values represent:
--   r = ordinary table
--   p = partitioned table
--   v = view
--   m = materialized view
--   f = foreign table
--   S = sequence
--   c = composite type
--
-- If any matching object exists, initialization is rejected.
-- This protects an already initialized database.

DO $bootstrap$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM pg_class c
        JOIN pg_namespace n
            ON n.oid = c.relnamespace
        WHERE n.nspname = 'public'
          AND c.relkind IN (
              'r', 'p', 'v', 'm', 'f', 'S', 'c'
          )
    ) THEN
        RAISE EXCEPTION
            'LimitGuard baseline requires an empty public schema';
END IF;
END
$bootstrap$;


