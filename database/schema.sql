-- ------------------------------------------------------------
-- TABLE 16: notification_outbox
-- ------------------------------------------------------------
-- Stores events created by the Credit Service.
--
-- Supports the transactional outbox pattern.
--
-- Example workflow:
--   1. A credit request is approved.
--   2. Credit Service saves the business change.
--   3. A notification event is stored in this table.
--   4. An outbox publisher sends the event to Kafka.
--   5. Activity Service can consume the event.
--
-- published_at:
--   Indicates when the event was published.
--
-- The CHECK constraint validates event-specific fields.
--
-- PostgreSQL functions used:
--
-- btrim(value):
--   Removes surrounding spaces from text.
--
-- num_nonnulls(...):
--   Counts how many supplied values are not NULL.
--
-- IS TRUE:
--   Requires the CASE result to be explicitly TRUE.
--   FALSE and NULL are both rejected.
--
-- These checks prevent malformed event records.

CREATE TABLE public.notification_outbox (
                                            id bigint GENERATED BY DEFAULT AS IDENTITY,
                                            created_at timestamp(6) without time zone NOT NULL,
                                            credit_request_id bigint,
                                            event_type varchar(255) NOT NULL,
                                            financial_institution_id bigint NOT NULL,
                                            published_at timestamp(6) without time zone,
                                            reason text,
                                            requester_id bigint,
                                            status varchar(255),
                                            counterparty_id bigint,
                                            credit_limit_id bigint,
                                            group_credit_limit_id bigint,
                                            corporate_group_id bigint,
                                            old_limit_amount numeric(19,2),
                                            new_limit_amount numeric(19,2),

                                            CONSTRAINT notification_outbox_event_fields_check
                                                CHECK (
                                                    (
                                                        CASE

                                                            -- Credit request events:
                                                            -- Require request ID, requester ID, and
                                                            -- a non-empty status.
                                                            --
                                                            -- Other event-specific fields must be NULL.

                                                            WHEN event_type IN (
                                                                                'CREDIT_REQUEST_CREATED',
                                                                                'CREDIT_REQUEST_APPROVED',
                                                                                'CREDIT_REQUEST_REJECTED',
                                                                                'CREDIT_REQUEST_USED',
                                                                                'CREDIT_REQUEST_CANCELLED',
                                                                                'CREDIT_REQUEST_EXPIRED'
                                                                )
                                                                THEN
                                                                credit_request_id IS NOT NULL
                                                                    AND requester_id IS NOT NULL
                                                                    AND btrim(status) <> ''
                                                                    AND num_nonnulls(
                                                                                counterparty_id,
                                                                                credit_limit_id,
                                                                                group_credit_limit_id,
                                                                                corporate_group_id,
                                                                                old_limit_amount,
                                                                                new_limit_amount
                                                                        ) = 0

                                                            -- Counterparty status events:
                                                            -- Require a counterparty ID and
                                                            -- an allowed status.
                                                            --
                                                            -- Unrelated event fields must be NULL.

                                                            WHEN event_type = 'COUNTERPARTY_STATUS_UPDATED'
                                                                THEN
                                                                counterparty_id IS NOT NULL
                                                                    AND status IN (
                                                                                   'ACTIVE',
                                                                                   'FROZEN',
                                                                                   'CLOSED'
                                                                    )
                                                                    AND num_nonnulls(
                                                                                credit_request_id,
                                                                                requester_id,
                                                                                credit_limit_id,
                                                                                group_credit_limit_id,
                                                                                corporate_group_id,
                                                                                old_limit_amount,
                                                                                new_limit_amount
                                                                        ) = 0

                                                            -- Individual credit limit updates:
                                                            -- Require the facility ID and both
                                                            -- the previous and new limit amounts.

                                                            WHEN event_type = 'CREDIT_LIMIT_UPDATED'
                                                                THEN
                                                                credit_limit_id IS NOT NULL
                                                                    AND old_limit_amount IS NOT NULL
                                                                    AND new_limit_amount IS NOT NULL
                                                                    AND num_nonnulls(
                                                                                credit_request_id,
                                                                                requester_id,
                                                                                status,
                                                                                counterparty_id,
                                                                                group_credit_limit_id,
                                                                                corporate_group_id
                                                                        ) = 0

                                                            -- Group credit limit updates:
                                                            -- Require the group facility ID,
                                                            -- corporate group ID, and old/new amounts.

                                                            WHEN event_type = 'GROUP_CREDIT_LIMIT_UPDATED'
                                                                THEN
                                                                group_credit_limit_id IS NOT NULL
                                                                    AND corporate_group_id IS NOT NULL
                                                                    AND old_limit_amount IS NOT NULL
                                                                    AND new_limit_amount IS NOT NULL
                                                                    AND num_nonnulls(
                                                                                credit_request_id,
                                                                                requester_id,
                                                                                status,
                                                                                counterparty_id,
                                                                                credit_limit_id
                                                                        ) = 0

                                                            -- Any unsupported event type is rejected.
                                                            ELSE false

                                                            END
                                                        ) IS TRUE
                                                    ),

                                            CONSTRAINT notification_outbox_pkey
                                                PRIMARY KEY (id)
);


