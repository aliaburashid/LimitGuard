-- ============================================================
-- 5. FOREIGN KEY RELATIONSHIPS
-- ============================================================
--
-- A foreign key connects records in different tables.
--
-- Example:
--   users.financial_institution_id
--       references
--   financial_institutions.id
--
-- This means a user cannot reference a bank that does
-- not exist in the financial_institutions table.
--
-- Foreign keys help maintain referential integrity.
--
-- All referenced tables have been created above.
-- We can now add their relationships.
--
